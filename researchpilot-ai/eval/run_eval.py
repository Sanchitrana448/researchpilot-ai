"""Reproducible evaluation. Run: python eval/run_eval.py

Offline extractive mode, fixed corpus, no randomness, so the numbers below
are identical on every machine. Writes RESULTS.md at the repo root.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import os

os.environ.pop("OPENAI_API_KEY", None)  # force the deterministic offline path

from app.agents import run_research  # noqa: E402
from app.retrieval import Index  # noqa: E402
from app.sample_data import EVAL_QUESTIONS, SAMPLE_DOCS  # noqa: E402


def main() -> None:
    idx = Index()
    for d in SAMPLE_DOCS:
        idx.add_document(d["text"], d["source"])

    rows, invalid, cov, hits, latencies, contradictions = [], 0, [], 0, [], 0
    for q, expected in EVAL_QUESTIONS:
        r = run_research(idx, q, top_k=6)
        sources = {e["source"] for e in r.evidence}
        hit = expected in sources
        hits += hit
        invalid += r.metrics["invalid_citations"]
        cov.append(r.metrics["citation_coverage"])
        latencies.append(r.metrics.get("latency_ms", 0))
        contradictions += len(r.contradictions)
        rows.append((q, expected, hit, r.metrics["citation_coverage"], r.metrics["invalid_citations"]))

    n = len(EVAL_QUESTIONS)
    out = [
        "# Evaluation results",
        "",
        "Generated by `python eval/run_eval.py`. Offline extractive mode, fixed corpus "
        f"({len(SAMPLE_DOCS)} documents, {idx.stats()['chunks']} chunks), {n} questions, no randomness.",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Retrieval hit rate (expected source in evidence) | {hits}/{n} |",
        f"| Invalid citations (marker with no matching evidence) | {invalid} |",
        f"| Mean citation coverage (cited / retrieved passages) | {sum(cov) / n:.2f} |",
        f"| Contradiction flags (corpus has one deliberate conflict, in the two chunking documents) | {contradictions} |",
        "",
        "| Question | Expected source | Hit | Coverage | Invalid |",
        "|---|---|---|---|---|",
    ]
    for q, e, h, c, i in rows:
        out.append(f"| {q} | {e} | {'yes' if h else 'no'} | {c:.2f} | {i} |")
    out += [
        "",
        "## Reading these numbers honestly",
        "",
        "- The corpus is small and was written for this demo, so a high hit rate shows the "
        "pipeline works end to end, not that it generalises.",
        "- Zero invalid citations is structural in offline mode: the extractive writer only "
        "emits passages it retrieved. The validator matters when an LLM writes the answer.",
        "- Retrieval is TF-IDF, so it matches on shared words, not meaning.",
        "",
    ]
    (ROOT / "RESULTS.md").write_text("\n".join(out))
    print("\n".join(out))
    if invalid:
        sys.exit(1)


if __name__ == "__main__":
    main()
