"""Paraphrase and refusal check. Run: python eval/retrieval_benchmark.py

A small hand-written test of two things the public SciFact benchmark does not
measure:
- reworded questions: each paraphrase query shares no content words with
  its target passage (checked in code), so keyword matching cannot find it;
- refusal: off-topic questions should retrieve nothing at all.

Compares vector search alone with vector search + cross-encoder re-ranking.
Returns markdown for eval/run_eval.py to put into RESULTS.md.
"""
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "eval"))

from app.retrieval import MIN_SIMILARITY, RELATIVE_MARGIN, TOPIC_GATE, Index  # noqa: E402
from benchmark_data import (  # noqa: E402
    KEYWORD_QUERIES,
    OFF_TOPIC_QUERIES,
    PARAPHRASE_QUERIES,
    PASSAGES,
    check_overlap,
)

PIPELINES = {"Vector search (bge-small + Qdrant)": False, "Vector search + cross-encoder re-rank": True}


def build_index() -> Index:
    idx = Index()
    for pid, text in PASSAGES.items():
        idx.add_document(text, f"{pid}.txt")
    return idx


def score(idx: Index, queries, rerank: bool) -> dict:
    r1 = r3 = 0
    rr = []
    for q, pid in queries:
        sources = [r["source"] for r in idx.search(q, top_k=10, rerank=rerank)]
        target = f"{pid}.txt"
        rank = sources.index(target) + 1 if target in sources else None
        r1 += rank == 1
        r3 += rank is not None and rank <= 3
        rr.append(1 / rank if rank else 0.0)
    n = len(queries)
    return {"r1": r1 / n, "r3": r3 / n, "mrr": sum(rr) / n}


def run() -> str:
    check_overlap()
    idx = build_index()
    n_off = len(OFF_TOPIC_QUERIES)
    rows = []
    for name, rerank in PIPELINES.items():
        t0 = time.perf_counter()
        kw = score(idx, KEYWORD_QUERIES, rerank)
        pa = score(idx, PARAPHRASE_QUERIES, rerank)
        refused = sum(not idx.is_on_topic(q) for q in OFF_TOPIC_QUERIES)
        answered = sum(idx.is_on_topic(q) for q, _ in KEYWORD_QUERIES + PARAPHRASE_QUERIES)
        ms = (time.perf_counter() - t0) * 1000 / (len(KEYWORD_QUERIES) + len(PARAPHRASE_QUERIES) + n_off)
        rows.append((name, kw, pa, refused, answered, ms))

    out = [
        "## Paraphrase and refusal check",
        "",
        f"Generated by `python eval/retrieval_benchmark.py`. {len(PASSAGES)} hand-written passages; "
        f"{len(KEYWORD_QUERIES)} keyword queries (share two or more content words with the target), "
        f"{len(PARAPHRASE_QUERIES)} paraphrase queries (share none, checked in code), {n_off} off-topic "
        f"questions that should be refused. Topic gate {TOPIC_GATE} on the question's best match; passage floor "
        f"{MIN_SIMILARITY}; passages kept within {RELATIVE_MARGIN} of the best match.",
        "",
        "| Pipeline | Keyword R@1 | Keyword MRR | Paraphrase R@1 | Paraphrase R@3 | Paraphrase MRR "
        "| On-topic answered | Off-topic refused | ms / query |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    n_on = len(KEYWORD_QUERIES) + len(PARAPHRASE_QUERIES)
    for name, kw, pa, refused, answered, ms in rows:
        out.append(
            f"| {name} | {kw['r1']:.2f} | {kw['mrr']:.2f} | {pa['r1']:.2f} | {pa['r3']:.2f} | {pa['mrr']:.2f} "
            f"| {answered}/{n_on} | {refused}/{n_off} | {ms:.0f} |"
        )
    out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    print(run())
